package fundamentos;

public class ConvencaoDeTiposPrimitivos {

    public static void main(String[] args) {
        
        double a = 1;
        System.out.println(a);

        float b = (float) 1.0;
        System.out.println(b);

        double c = 1.123456789;
        System.out.println(c);

        float d = (float) 1.123456789;
        System.out.println(d);



    }

}
